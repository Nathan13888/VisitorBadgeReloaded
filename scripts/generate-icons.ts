/**
 * Generates `src/generated/simple-icons.ts`, the icon set the badge renderer
 * draws logos from.
 *
 * The whole set is ~4.7MB of SVG path data, which is well within a Worker's
 * size budget but not something we want to hand to `JSON.parse` on every cold
 * start. So it is emitted as one flat string plus an index of
 * `key -> [offset, length]`: the index parses in well under a millisecond and
 * a lookup is a single `slice`.
 *
 * The index also decides which names resolve. Simple Icons only exports
 * canonical slugs (`googlechrome`), while Shields additionally accepts the
 * hyphenated title (`google-chrome`), so badges in the wild use both. We keep
 * both, then add Simple Icons' own alias metadata on top - see the tier
 * comments below.
 *
 * Run with `bun run gen:icons` (`--force` to regenerate an up-to-date file).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import * as simpleIcons from "simple-icons";
import { titleToSlug } from "simple-icons/sdk";

type IconAliases = {
  aka?: string[];
  old?: string[];
  loc?: Record<string, string>;
  dup?: { title: string }[];
};

type IconMetadata = {
  slug: string;
  aliases?: IconAliases;
};

const require = createRequire(import.meta.url);
const iconsDataPath = require.resolve("simple-icons/icons.json");
const iconsData = require(iconsDataPath) as IconMetadata[];
const { version } = JSON.parse(
  readFileSync(join(dirname(iconsDataPath), "..", "package.json"), "utf8"),
) as { version: string };

const OUT_DIR = join(import.meta.dir, "..", "src", "generated");
const OUT_FILE = join(OUT_DIR, "simple-icons.ts");

/** Matches the lookup key Shields derives from a user-supplied logo name. */
const toLookupKey = (name: string) => name.toLowerCase().replace(/ /g, "-");

const isUpToDate = () => {
  if (!existsSync(OUT_FILE)) {
    return false;
  }
  const head = readFileSync(OUT_FILE, "utf8").slice(0, 512);
  return head.includes(`SIMPLE_ICONS_VERSION = "${version}"`);
};

if (isUpToDate() && !process.argv.includes("--force")) {
  console.log(`icons: up to date with simple-icons@${version}`);
  process.exit(0);
}

const icons = Object.values(simpleIcons);

// Records are `<6 char hex><the icon's SVG minus its opening `<svg`>`,
// concatenated into one blob. Keeping the tail verbatim rather than rebuilding
// it from the path is what makes the rendered logo byte-identical to Shields',
// which colours icons by splicing a fill straight after `<svg`.
const blob: string[] = [];
const records = new Map<string, [number, number]>();
let offset = 0;
for (const icon of icons) {
  const record = icon.hex + icon.svg.slice("<svg".length);
  records.set(icon.slug, [offset, record.length]);
  blob.push(record);
  offset += record.length;
}

// Lowest to highest precedence, later tiers overwrite earlier ones.
const index = new Map<string, [number, number]>();
const claim = (name: string, slug: string) => {
  const record = records.get(slug);
  const key = toLookupKey(name);
  if (record && key) {
    index.set(key, record);
  }
};

// Tier 3: Simple Icons' own alias metadata. Shields ignores this, so these
// names render blank there today - resolving them is purely additive.
for (const { slug, aliases } of iconsData) {
  if (!aliases) {
    continue;
  }
  const titles = [
    ...(aliases.aka ?? []),
    ...(aliases.old ?? []),
    ...Object.values(aliases.loc ?? {}),
    ...(aliases.dup ?? []).map((entry) => entry.title),
  ];
  for (const title of titles) {
    // Both the hyphenated form Shields-style names use and the canonical
    // slugification Simple Icons would have given the alias.
    claim(title, slug);
    claim(titleToSlug(title), slug);
  }
}

// Tier 2: the hyphenated title, which is how Shields has always accepted
// multi-word logos (`google-chrome`, `visual-studio-code`).
for (const icon of icons) {
  claim(icon.title, icon.slug);
}

// Tier 1: canonical slugs always win, so a title that collides with another
// icon's slug can never shadow it.
for (const icon of icons) {
  claim(icon.slug, icon.slug);
}

const indexJson = JSON.stringify(Object.fromEntries(index));
const contents = `// Generated by scripts/generate-icons.ts. Do not edit.
export const SIMPLE_ICONS_VERSION = ${JSON.stringify(version)};

/** Every icon's brand hex followed by its SVG, minus the opening \`<svg\`. */
export const ICON_BLOB = ${JSON.stringify(blob.join(""))};

/** Lookup key -> [offset, length] into {@link ICON_BLOB}, parsed on first use. */
export const ICON_INDEX_JSON = ${JSON.stringify(indexJson)};
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, contents);

const mb = (bytes: number) => `${(bytes / 1e6).toFixed(2)}MB`;
console.log(
  `icons: simple-icons@${version}, ${icons.length} icons, ${index.size} lookup keys, ${mb(contents.length)}`,
);
